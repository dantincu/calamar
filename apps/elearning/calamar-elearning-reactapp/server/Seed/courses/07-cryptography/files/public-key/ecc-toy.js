// ecc-toy.js: elliptic-curve arithmetic on a curve small enough to check by hand,
// ECDH and ECDSA on it, and the classic ECDSA nonce-reuse key recovery.
//   node ecc-toy.js
//
// Curve: y^2 = x^3 + 2x + 2 over the field F_17. Generator G = (5, 1), whose order is n = 19 (prime).
// Real curves use the same formulas with 256-bit numbers (P-256, secp256k1), or the faster
// equivalent forms of Curve25519.
import { mod, modInverse } from '../math/modmath.js';

const p = 17n, A = 2n, B = 2n;
const G = { x: 5n, y: 1n };
const O = null;                                   // the point at infinity: the group's identity element

const onCurve = (P) => P === O || mod(P.y * P.y - (P.x ** 3n + A * P.x + B), p) === 0n;
const eq = (P, Q) => P === Q || (P !== O && Q !== O && P.x === Q.x && P.y === Q.y);
const show = (P) => (P === O ? 'O' : `(${P.x}, ${P.y})`);

/** P + Q with the chord-and-tangent rule */
function add(P, Q) {
  if (P === O) return Q;
  if (Q === O) return P;
  if (P.x === Q.x && mod(P.y + Q.y, p) === 0n) return O;          // P + (-P) = O
  const lambda = eq(P, Q)
    ? mod((3n * P.x * P.x + A) * modInverse(2n * P.y, p), p)        // tangent slope (doubling)
    : mod((Q.y - P.y) * modInverse(Q.x - P.x, p), p);              // chord slope
  const x = mod(lambda * lambda - P.x - Q.x, p);
  const y = mod(lambda * (P.x - x) - P.y, p);
  return { x, y };
}

/** k * P by double-and-add (real implementations use constant-time ladders instead) */
function mul(k, P) {
  let R = O;
  for (let bit of k.toString(2)) {
    R = add(R, R);
    if (bit === '1') R = add(R, P);
  }
  return R;
}

// ---- The group generated by G ---------------------------------------------------------------------------
const multiples = [];
for (let k = 1n, P = G; ; k++, P = add(P, G)) {
  multiples.push(`${k}G=${show(P)}`);
  if (P === O) break;
}
console.log('Multiples of G:', multiples.join('  '));
console.log(`So G has order n = ${multiples.length}; every point is on the curve: ${[...Array(19)].every((_, i) => onCurve(mul(BigInt(i + 1), G)))}`);
console.log(`Check by hand: G + G = ${show(add(G, G))}; 2G + G = ${show(add(add(G, G), G))}`);

const n = 19n;

// ---- ECDH ----------------------------------------------------------------------------------------------
const a = 7n, b = 11n;                                   // private keys
const Apub = mul(a, G), Bpub = mul(b, G);                // public keys
console.log(`\nECDH: Alice a=${a}, A=aG=${show(Apub)}; Bob b=${b}, B=bG=${show(Bpub)}`);
console.log(`  Alice computes aB = ${show(mul(a, Bpub))}, Bob computes bA = ${show(mul(b, Apub))}: the same point`);

// ---- ECDSA ---------------------------------------------------------------------------------------------
// sign(z): r = (kG).x mod n, s = k^-1 (z + r d) mod n.   verify: u1 = z s^-1, u2 = r s^-1, check (u1 G + u2 Q).x = r
function sign(z, d, k) {
  const R = mul(k, G);
  const r = mod(R.x, n);
  const s = mod(modInverse(k, n) * (z + r * d), n);
  if (r === 0n || s === 0n) throw new Error('pick another k');
  return { r, s };
}
function verify(z, { r, s }, Q) {
  const w = modInverse(s, n);
  const X = add(mul(mod(z * w, n), G), mul(mod(r * w, n), Q));
  return X !== O && mod(X.x, n) === r;
}

const d = 13n, Q = mul(d, G);                            // signing key and public key
const z1 = 5n, z2 = 9n;                                  // two message hashes (reduced mod n)
const sig1 = sign(z1, d, 3n);
console.log(`\nECDSA: d=${d}, Q=dG=${show(Q)}; signature of z=${z1} with k=3: (r, s) = (${sig1.r}, ${sig1.s})`);
console.log(`  valid? ${verify(z1, sig1, Q)}; valid for another message? ${verify(z2, sig1, Q)}`);

// ---- The nonce-reuse disaster ------------------------------------------------------------------------------
// Two signatures with the SAME k share r. From s1 - s2 = k^-1 (z1 - z2):  k = (z1 - z2) / (s1 - s2),  then d = (s k - z) / r.
const k = 3n;
const s1 = sign(z1, d, k), s2 = sign(z2, d, k);
const kRecovered = mod((z1 - z2) * modInverse(s1.s - s2.s, n), n);
const dRecovered = mod((s1.s * kRecovered - z1) * modInverse(s1.r, n), n);
console.log(`\nNonce reuse: two signatures share r = ${s1.r} (that's how it's spotted)`);
console.log(`  recovered k = ${kRecovered}, recovered private key d = ${dRecovered} (the real d is ${d})`);
